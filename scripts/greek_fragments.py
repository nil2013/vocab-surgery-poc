#!/usr/bin/env python3
"""Write a deletion list of Greek word fragments from a plan's tokens.jsonl.

A surviving, unprotected token is listed when it has at least three Greek letters, or at least two with an accent
(tonos, dialytika or polytonic marks). Single letters and unaccented pairs stay for mathematical use.
Needs the `regex` module for Script=Greek (Unicode 17 data).
"""
import argparse
import json
from pathlib import Path

import regex

GREEK = regex.compile(r"\p{Script=Greek}")
ACCENTED = regex.compile(r"[ΆΈ-ΐΪ-ΰϊ-ώἀ-῿]")


def selected(surface):
    letters = len(GREEK.findall(surface))
    return letters >= 3 or (letters >= 2 and ACCENTED.search(surface) is not None)


def fragments(lines):
    for line in lines:
        token = json.loads(line)
        if token["compactId"] is not None and token["surface"] is not None and not token["protection"] and selected(token["surface"]):
            yield token["surface"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tokens", type=Path, help="tokens.jsonl of a plan run")
    parser.add_argument("output", type=Path, help="new deletion list file")
    args = parser.parse_args()
    with args.tokens.open(encoding="utf-8") as stream:
        entries = sorted(set(fragments(stream)))
    with args.output.open("x", encoding="utf-8") as out:
        out.write(f"# Greek fragments: >=3 Greek letters, or >=2 with an accent ({len(entries)} entries)\n")
        out.write(f"# Generated by scripts/greek_fragments.py from {args.tokens.parent.name}/tokens.jsonl\n")
        for entry in entries:
            out.write(json.dumps(entry, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
